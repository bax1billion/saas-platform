/**
 * Writes each data domain's model introspection schema to
 * lib/data-domains/<domain>.introspection.json and the index that imports
 * them (lib/data-domains/introspections.ts), from the domain registry
 * (docs/data-domains.md § 3.3). Amplify delivers the foundation API's
 * introspection through amplify_outputs.json; a domain API's cannot ride a
 * CloudFormation output (1,024 bytes), so it is generated, committed like
 *, and held current by lib/data-domains/introspection.test.ts.
 *
 * Usage: npm run generate:domains   (node --import tsx scripts/generate-domains.mjs)
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateModelsSync } from "@aws-amplify/graphql-generator";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Every module composed: the introspection is the whole domain, whatever this deploy composes.
delete process.env.BACKEND_MODULES;
const { DATA_DOMAINS, domainSchemas } = await import("../amplify/data/domains/registry.ts");

const lines = [
  "// Generated by `npm run generate:domains` from amplify/data/domains/registry.ts; do not edit.",
  "// The model introspection of each data domain's API, for the typed client (lib/data-client.ts).",
];
const EMPTY = { version: 1, models: {}, enums: {}, nonModels: {} };
for (const id of DATA_DOMAINS) {
  const sdl = domainSchemas[id].transform().schema;
  // A domain with no module yet has an empty schema; its client has nothing to type.
  const parsed = sdl.trim() ? JSON.parse(generateModelsSync({ schema: sdl, target: "introspection" })["model-introspection.json"]) : EMPTY;
  const out = join(root, "lib", "data-domains", `${id}.introspection.json`);
  writeFileSync(out, `${JSON.stringify(parsed, null, 2)}\n`);
  lines.push(`import ${id} from "./${id}.introspection.json";`);
  console.log(`✓ ${id}: ${Object.keys(parsed.models).length} models → ${out.slice(root.length + 1)}`);
}
lines.push("", `export const introspections = { ${DATA_DOMAINS.join(", ")} } as const;`, "");
writeFileSync(join(root, "lib", "data-domains", "introspections.ts"), lines.join("\n"));
console.log("✓ lib/data-domains/introspections.ts");
